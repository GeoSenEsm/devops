#!/usr/bin/env bash
#
# GeoSenEsm — undo what deploy.sh set up for one or more instances, e.g. to
# clean up after a failed install before trying again.
#
# By default it stops and removes the instance's containers and its Nginx
# site, and keeps the data (SQL Server, MongoDB, uploads) plus .env, so a
# later deploy.sh run picks up where it left off. Add --delete-data to wipe
# everything and start from scratch.
#
# Never touched: Docker/Nginx/certbot packages, the shared privacy-policy
# folder, and other instances.
#
# Examples
# --------
#   ./undeploy.sh                                  # default instance (geosenesm)
#   ./undeploy.sh --names shop,lab                 # instances from deploy.sh --names
#   ./undeploy.sh --name staging --delete-data --delete-certs
#
set -euo pipefail

NAMES=""
DEPLOY_DIR=""
DELETE_DATA=false
DELETE_CERTS=false
ASSUME_YES=false

SCRIPT_NAME="$(basename "$0")"

log()  { printf '\033[1;32m[undeploy]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[undeploy]\033[0m %s\n' "$*" >&2; }
err()  { printf '\033[1;31m[undeploy]\033[0m %s\n' "$*" >&2; exit 1; }

is_tty() { [ -t 0 ]; }
require_cmd() { command -v "$1" >/dev/null 2>&1; }

usage() {
  cat <<EOF
Usage: $SCRIPT_NAME [options]

  --name NAME                Instance to remove (default: geosenesm).
  --names N1,N2,...          Several instances, e.g. the ones created with
                              deploy.sh --names.
  --deploy-dir DIR           Deploy dir, if deploy.sh was given --deploy-dir
                              (default: \$HOME/NAME). Single instance only.
  --delete-data              Also delete the database, uploads and the whole
                              deploy dir (.env included). Cannot be undone.
  --delete-certs             Also delete the Let's Encrypt certificate. Keep it
                              if you will deploy again soon — Let's Encrypt
                              limits how often a certificate can be reissued.
  -y, --yes                  Don't ask for confirmation.
  -h, --help                 Show this help.
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --name|--names) NAMES="${NAMES:+$NAMES,}$2"; shift 2 ;;
    --deploy-dir) DEPLOY_DIR="$2"; shift 2 ;;
    --delete-data) DELETE_DATA=true; shift ;;
    --delete-certs) DELETE_CERTS=true; shift ;;
    -y|--yes) ASSUME_YES=true; shift ;;
    -h|--help) usage; exit 0 ;;
    *) err "Unknown option: $1 (see --help)" ;;
  esac
done

IFS=', ' read -r -a instances <<< "${NAMES:-geosenesm}"
for name in "${instances[@]}"; do
  [[ "$name" =~ ^[a-z0-9][a-z0-9_-]*$ ]] || err "Instance names must be lowercase letters, digits, '-' or '_' (got: $name)."
done
if [ -n "$DEPLOY_DIR" ] && [ ${#instances[@]} -gt 1 ]; then
  err "--deploy-dir works with a single instance only."
fi

DOCKER=""
if require_cmd docker; then
  DOCKER="docker"
  docker version >/dev/null 2>&1 || DOCKER="sudo docker"
fi

deploy_dir_of() {
  printf '%s' "${DEPLOY_DIR:-${HOME:-.}/$1}"
}

# Only delete folders deploy.sh created, never an arbitrary --deploy-dir.
is_generated_dir() {
  grep -qs '^# Generated by deploy.sh' "$1/.env"
}

cert_name_of() {
  [ -f "$1/.env" ] || return 0
  sed -n 's#^API_URL=https://##p' "$1/.env"
}

# ---------------------------------------------------------------------------
# Show the plan and confirm
# ---------------------------------------------------------------------------
log "This will remove:"
for name in "${instances[@]}"; do
  dir="$(deploy_dir_of "$name")"
  echo "  [$name]"
  echo "    - Docker containers and network of project '$name'"
  [ -e "/etc/nginx/sites-available/$name" ] && echo "    - Nginx site /etc/nginx/sites-available/$name"
  if [ "$DELETE_CERTS" = true ] && [ -n "$(cert_name_of "$dir")" ]; then
    echo "    - Let's Encrypt certificate $(cert_name_of "$dir")"
  fi
  if [ "$DELETE_DATA" = true ]; then
    echo "    - ALL DATA: Docker volumes and $dir"
  else
    echo "    (keeping data and $dir)"
  fi
done

if [ "$ASSUME_YES" != true ]; then
  is_tty || err "Not running interactively — re-run with --yes to confirm."
  if [ "$DELETE_DATA" = true ]; then
    read -r -p "Data will be lost. Type the instance name(s) to confirm (${instances[*]}): " answer
    [ "$answer" = "${instances[*]}" ] || err "Confirmation did not match — nothing removed."
  else
    read -r -p "Continue? [y/N] " answer
    [[ "$answer" =~ ^[Yy] ]] || err "Aborted — nothing removed."
  fi
fi

# ---------------------------------------------------------------------------
# Remove
# ---------------------------------------------------------------------------
nginx_changed=false

for name in "${instances[@]}"; do
  dir="$(deploy_dir_of "$name")"
  log "=== Instance: $name ==="

  if [ -z "$DOCKER" ]; then
    warn "Docker not installed — no containers to remove."
  else
    down_args=(down --remove-orphans)
    [ "$DELETE_DATA" = true ] && down_args+=(--volumes)
    if [ -f "$dir/docker-compose.yml" ]; then
      # Inside the deploy dir Compose takes the project name from .env, as deploy.sh did.
      (cd "$dir" && $DOCKER compose "${down_args[@]}") || warn "docker compose down failed for $name."
    else
      $DOCKER compose -p "$name" "${down_args[@]}" || warn "docker compose down failed for $name."
    fi
  fi

  if [ -e "/etc/nginx/sites-available/$name" ] || [ -L "/etc/nginx/sites-enabled/$name" ]; then
    sudo rm -f "/etc/nginx/sites-enabled/$name" "/etc/nginx/sites-available/$name"
    nginx_changed=true
    log "Removed Nginx site $name."
  fi

  cert_name="$(cert_name_of "$dir")"
  if [ "$DELETE_CERTS" = true ] && [ -n "$cert_name" ] && require_cmd certbot; then
    sudo certbot delete --cert-name "$cert_name" --non-interactive \
      || warn "certbot could not delete $cert_name — list certificates with: sudo certbot certificates"
  fi

  if [ "$DELETE_DATA" = true ]; then
    if [ ! -d "$dir" ]; then
      log "No deploy dir at $dir."
    elif is_generated_dir "$dir"; then
      # SQL Server writes its files as its own container user, so plain rm may be refused.
      rm -rf "$dir" 2>/dev/null || sudo rm -rf "$dir"
      log "Deleted $dir."
    else
      warn "$dir has no .env generated by deploy.sh — left it alone. Delete it by hand if it is safe."
    fi
  fi
done

if [ "$nginx_changed" = true ]; then
  sudo nginx -t && { sudo nginx -s reload 2>/dev/null || sudo systemctl reload nginx; } \
    || warn "Nginx config test failed after removing the site(s) — check: sudo nginx -t"
fi

log "Done. Re-deploy any time with deploy.sh."
